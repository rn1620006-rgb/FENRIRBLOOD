CREATE TABLE IF NOT EXISTS media (
 id TEXT PRIMARY KEY, uploader_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 file_name TEXT NOT NULL, bytes INTEGER NOT NULL,
 width INTEGER NOT NULL, height INTEGER NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS post_media (
 post_id TEXT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 media_id TEXT NOT NULL UNIQUE REFERENCES media(id) ON DELETE CASCADE,
 position INTEGER NOT NULL, PRIMARY KEY(post_id,media_id)
);
CREATE TABLE IF NOT EXISTS hall_awards (
 id TEXT PRIMARY KEY, member_id TEXT NOT NULL REFERENCES users(id),
 title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 awarded_by TEXT NOT NULL REFERENCES users(id), awarded_at TEXT NOT NULL
);
